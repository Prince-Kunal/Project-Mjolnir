// Writes pgTAP tests from the case tables in packages/domain, so the SQL versions of the rules
// are checked against the same cases as the TypeScript ones (plan section 6):
//   scoring.cases.json  -> supabase/tests/03_scoring_cases.test.sql
//   streaks.cases.json  -> supabase/tests/05_streak_cases.test.sql
//   suggestions.cases.json -> supabase/tests/10_suggestion_cases.test.sql
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url);
const read = (name) =>
  JSON.parse(readFileSync(new URL(`packages/domain/src/${name}`, root), 'utf8'));
const write = (name, lines) =>
  writeFileSync(new URL(`supabase/tests/${name}`, root), lines.join('\n'));
const q = (s) => `'${String(s).replaceAll("'", "''")}'`;
const header = (source) => [
  `-- Generated by scripts/gen-shared-tests.mjs from packages/domain/src/${source}.`,
  '-- Do not edit by hand: run `pnpm gen:shared-tests`.',
  'begin;',
];

function scoring() {
  const cases = read('scoring.cases.json');
  const user = '33333333-3333-3333-3333-333333333333';
  const dateFor = (i) => `2026-01-${String(i + 1).padStart(2, '0')}`;
  const lines = [
    ...header('scoring.cases.json'),
    `select plan(${cases.bands.length + cases.days.length});`,
    '',
    `insert into auth.users (id, email) values (${q(user)}, 'score@example.com');`,
    '',
  ];
  for (const b of cases.bands) {
    lines.push(
      `select is(public.score_band(${b.rate}), ${q(b.band)}, ${q(`${b.rate}% is ${b.band}`)});`,
    );
  }
  lines.push('');
  cases.days.forEach((d, i) => {
    for (const item of d.items) {
      lines.push(
        `insert into public.items (user_id, source, title, points, status, logical_date) values ` +
          `(${q(user)}, 'manual', 'case', ${item.points}, ${q(item.status)}, ${q(dateFor(i))});`,
      );
    }
    const want = JSON.stringify({
      planned: d.planned,
      done: d.done,
      missed: d.missed,
      rate: d.rate,
      band: d.band,
    });
    lines.push(
      `select is(private.day_score(${q(user)}, ${q(dateFor(i))}), ${q(want)}::jsonb, ${q(d.name)});`,
    );
  });
  lines.push('', 'select * from finish();', 'rollback;', '');
  write('03_scoring_cases.test.sql', lines);
}

function streaks() {
  const { cases } = read('streaks.cases.json');
  const lines = [...header('streaks.cases.json'), `select plan(${cases.length * 3});`, ''];
  cases.forEach((c, i) => {
    const user = `44444444-4444-4444-4444-${String(i).padStart(12, '0')}`;
    lines.push(
      `-- ${c.name}`,
      `insert into auth.users (id, email) values (${q(user)}, 'streak${i}@example.com');`,
      `update public.profiles set week_start = ${c.weekStart ?? 1} where id = ${q(user)};`,
    );
    for (const [date, rate] of c.days) {
      lines.push(
        `insert into public.day_summaries (user_id, logical_date, planned_points, done_points, missed_points, ` +
          `success_rate, band, finalized_at) values (${q(user)}, ${q(date)}, 10, 0, 0, ${rate}, ` +
          `public.score_band(${rate}), now());`,
      );
    }
    lines.push(
      `select private.recompute_streak(${q(user)}, ${q(c.days[0][0])});`,
      `select is((select array_agg(streak_after order by logical_date) from public.day_summaries where user_id = ${q(user)}), ` +
        `array[${c.streak.join(', ')}], ${q(`${c.name}: streak`)});`,
      `select is((select array_agg(rest_pass_used order by logical_date) from public.day_summaries where user_id = ${q(user)}), ` +
        `array[${c.pass.join(', ')}], ${q(`${c.name}: rest pass`)});`,
      `select is((select array[current, best] from public.streak_state where user_id = ${q(user)}), ` +
        `array[${c.current}, ${c.best}], ${q(`${c.name}: current and best`)});`,
      '',
    );
  });
  lines.push('select * from finish();', 'rollback;', '');
  write('05_streak_cases.test.sql', lines);
}

function suggestions() {
  const { cases } = read('suggestions.cases.json');
  const lines = [...header('suggestions.cases.json'), `select plan(${cases.length});`, ''];
  for (const c of cases) {
    lines.push(
      `select is(private.title_has_tag(${q(c.title)}, ${q(c.tag)}), ${c.match}, ${q(c.name)});`,
    );
  }
  lines.push('', 'select * from finish();', 'rollback;', '');
  write('10_suggestion_cases.test.sql', lines);
}

scoring();
streaks();
suggestions();
