// Writes supabase/tests/03_scoring_cases.test.sql from packages/domain/src/scoring.cases.json, so
// the SQL score functions are checked against the same cases as the TypeScript ones (plan 6).
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url);
const cases = JSON.parse(
  readFileSync(new URL('packages/domain/src/scoring.cases.json', root), 'utf8'),
);
const user = '33333333-3333-3333-3333-333333333333';
const q = (s) => `'${String(s).replaceAll("'", "''")}'`;
const dateFor = (i) => `2026-01-${String(i + 1).padStart(2, '0')}`;

const lines = [
  '-- Generated by scripts/gen-score-tests.mjs from packages/domain/src/scoring.cases.json.',
  '-- Do not edit by hand: run `pnpm gen:score-tests`.',
  'begin;',
  `select plan(${cases.bands.length + cases.days.length});`,
  '',
  `insert into auth.users (id, email) values (${q(user)}, 'score@example.com');`,
  '',
];

for (const b of cases.bands) {
  lines.push(
    `select is(public.score_band(${b.rate}), ${q(b.band)}, ${q(`${b.rate}% is ${b.band}`)});`,
  );
}
lines.push('');

cases.days.forEach((d, i) => {
  for (const item of d.items) {
    lines.push(
      `insert into public.items (user_id, source, title, points, status, logical_date) values ` +
        `(${q(user)}, 'manual', 'case', ${item.points}, ${q(item.status)}, ${q(dateFor(i))});`,
    );
  }
  const want = JSON.stringify({
    planned: d.planned,
    done: d.done,
    missed: d.missed,
    rate: d.rate,
    band: d.band,
  });
  lines.push(
    `select is(private.day_score(${q(user)}, ${q(dateFor(i))}), ${q(want)}::jsonb, ${q(d.name)});`,
  );
});

lines.push('', 'select * from finish();', 'rollback;', '');
writeFileSync(new URL('supabase/tests/03_scoring_cases.test.sql', root), lines.join('\n'));
